export interface CultureNode {
  id: string;
  name: string;
  domain: Domain;
  tier: 1 | 2 | 3 | 4;
  cost: number;
  /** all of these */
  requires: string[];
  /** at least one of these (from any domain) */
  requiresAny: string[];
  /** exclusive fork: taking one node of a fork locks the others */
  fork?: string;
  tags: string[];
  mods: Partial<Mods>;
  /** tension added to the domain when taken */
  tension: number;
  note: string;
}

const COST = [0, 30, 70, 140, 240];
const TENSION = [0, 6, 10, 14, 20];

function n(
  domain: Domain,
  id: string,
  name: string,
  tier: CultureNode['tier'],
  tags: string[],
  mods: Partial<Mods>,
  note: string,
  o: { req?: string[]; any?: string[]; fork?: string; tension?: number } = {},
): CultureNode {
  return {
    id,
    name,
    domain,
    tier,
    cost: COST[tier],
    requires: o.req ?? [],
    requiresAny: o.any ?? [],
    fork: o.fork,
    tags,
    mods,
    tension: o.tension ?? TENSION[tier],
    note,
  };
}

